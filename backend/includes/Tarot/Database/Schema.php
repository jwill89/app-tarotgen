<?php

namespace Tarot\Database;

use PDO;
use PDOStatement;
use Phinx\Config\Config;
use Phinx\Migration\Manager;
use RuntimeException;
use Symfony\Component\Console\Input\ArrayInput;
use Symfony\Component\Console\Output\NullOutput;

/**
 * The schema's one source is db/migrations, run by Phinx with phinx.php's
 * settings. db/schema.sql is generated from them: build() runs every migration
 * on a throwaway database and dumps the result, and scripts/dump_schema.php
 * writes that to the file. The tests load the file; SchemaTest fails when it
 * isn't what the migrations build.
 */
final class Schema
{
    /** Phinx's record of the migrations that have run; not part of the app's schema. */
    public const string LOG_TABLE = 'phinxlog';

    private const string CONFIG = __DIR__ . '/../../../phinx.php';

    private const string HEADER = "-- TarotGen.io database schema (SQLite): what the migrations in db/migrations build.\n"
        . "-- Generated by `php scripts/dump_schema.php`. Don't edit it: add a migration.\n"
        . "\nPRAGMA foreign_keys = ON;\n";

    /**
     * Run the migrations that haven't run yet on the SQLite file at $path, with
     * phinx.php's settings. The file must exist (an empty one gets the whole
     * schema); Phinx never creates one.
     */
    public static function migrate(string $path): void
    {
        /** @var array{environments: array{app: array<string,string>}} $values */
        $values = require self::CONFIG;
        $values['environments']['app']['name'] = $path;

        $manager = new Manager(new Config($values), new ArrayInput([]), new NullOutput());
        try {
            $manager->migrate('app');
        } finally {
            // Closes the file, rolling back a migration that threw, so the
            // caller can open or delete it.
            $manager->getEnvironment('app')->getAdapter()->disconnect();
        }
    }

    /** The db/schema.sql text: every migration run on an empty throwaway database, dumped. */
    public static function build(): string
    {
        $dir = sys_get_temp_dir() . '/tarot-schema-' . bin2hex(random_bytes(4));
        mkdir($dir);
        $path = $dir . '/tarotdb.db';
        touch($path);

        try {
            self::migrate($path);
            $db = new PDO('sqlite:' . $path);
            $sql = self::dump($db);
            unset($db);

            return $sql;
        } finally {
            unlink($path);
            rmdir($dir);
        }
    }

    /**
     * $db's schema as SQL: each object's CREATE statement in the order it was
     * created, and after each table the rows it holds (in a freshly migrated
     * database, the migrations' seed rows). Phinx's log table is left out.
     */
    public static function dump(PDO $db): string
    {
        $objects = self::run($db, sprintf(
            "SELECT type, name, sql FROM sqlite_master
             WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite\\_%%' ESCAPE '\\' AND tbl_name <> '%s'
             ORDER BY rowid",
            self::LOG_TABLE,
        ))->fetchAll(PDO::FETCH_ASSOC);

        $out = self::HEADER;
        foreach ($objects as $object) {
            $out .= "\n" . trim((string) $object['sql']) . ";\n";
            if ($object['type'] === 'table') {
                $out .= self::rows($db, (string) $object['name']);
            }
        }

        return $out;
    }

    /** A table's rows as one INSERT, or nothing for an empty table. */
    private static function rows(PDO $db, string $table): string
    {
        /** @var list<array<string,mixed>> $rows */
        $rows = self::run($db, "SELECT * FROM \"{$table}\"")->fetchAll(PDO::FETCH_ASSOC);
        if ($rows === []) {
            return '';
        }

        $values = array_map(
            static fn(array $row): string => '    (' . implode(', ', array_map(self::literal(...), $row)) . ')',
            $rows,
        );

        return "\nINSERT INTO {$table} (" . implode(', ', array_keys($rows[0])) . ") VALUES\n"
            . implode(",\n", $values) . ";\n";
    }

    private static function literal(mixed $value): string
    {
        return match (true) {
            $value === null => 'NULL',
            is_int($value) => (string) $value,
            is_float($value) => var_export($value, true),
            default => "'" . str_replace("'", "''", (string) $value) . "'",
        };
    }

    private static function run(PDO $db, string $sql): PDOStatement
    {
        $stmt = $db->query($sql);
        if ($stmt === false) {
            throw new RuntimeException('Query failed: ' . $sql);
        }

        return $stmt;
    }
}
